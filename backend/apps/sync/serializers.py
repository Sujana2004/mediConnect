class SyncActionInputSerializer(serializers.Serializer):
    """
    Serializer for incoming sync action from frontend.
    """
    client_action_id = serializers.CharField(
        max_length=100,
        help_text="Unique ID generated by frontend"
    )
    action_type = serializers.ChoiceField(
        choices=[choice[0] for choice in SyncAction.ACTION_TYPES],
        help_text="Type of action"
    )
    data = serializers.JSONField(
        help_text="Action payload data"
    )
    client_timestamp = serializers.DateTimeField(
        required=False,
        help_text="When action was created on client"
    )
    resource_type = serializers.CharField(
        max_length=50,
        required=False,
        allow_blank=True,
        help_text="Type of resource being modified"
    )
    resource_id = serializers.CharField(
        max_length=100,
        required=False,
        allow_blank=True,
        help_text="ID of resource being modified"
    )
    resource_version = serializers.IntegerField(
        required=False,
        default=1,
        help_text="Version of resource when action was created"
    )
    
    def validate_client_timestamp(self, value):
        """Ensure timestamp is not in the future."""
        if value and value > timezone.now():
            # Allow some tolerance for clock differences
            max_future = timezone.now() + timezone.timedelta(minutes=5)
            if value > max_future:
                raise serializers.ValidationError(
                    "Timestamp cannot be more than 5 minutes in the future"
                )
        return value


