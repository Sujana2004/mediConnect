class ResolveConflictRequestSerializer(serializers.Serializer):
    """
    Serializer for conflict resolution request.
    """
    resolution = serializers.ChoiceField(
        choices=['use_server', 'use_client', 'merge', 'discard'],
        help_text="How to resolve the conflict"
    )
    custom_data = serializers.JSONField(
        required=False,
        allow_null=True,
        help_text="Custom merged data (required for 'merge' resolution)"
    )
    
    def validate(self, data):
        """Validate resolution request."""
        if data['resolution'] == 'merge' and not data.get('custom_data'):
            raise serializers.ValidationError({
                'custom_data': "Custom data is required for 'merge' resolution"
            })
        return data


