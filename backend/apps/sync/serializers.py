class PullRequestSerializer(serializers.Serializer):
    """
    Serializer for pull sync request.
    """
    since = serializers.DateTimeField(
        required=False,
        help_text="Only get data modified after this timestamp"
    )
    data_types = serializers.ListField(
        child=serializers.CharField(),
        required=False,
        help_text="List of data types to pull (empty = all)"
    )
    full_sync = serializers.BooleanField(
        required=False,
        default=False,
        help_text="If true, ignore 'since' and get all data"
    )
    
    def validate_data_types(self, value):
        """Validate data types."""
        valid_types = [
            'appointments', 'consultations', 'prescriptions',
            'reminders', 'health_profile', 'vital_signs',
            'conditions', 'allergies', 'vaccinations',
            'documents', 'emergency_contacts', 'notifications',
            'chat_sessions'
        ]
        
        if value:
            invalid = [dt for dt in value if dt not in valid_types]
            if invalid:
                raise serializers.ValidationError(
                    f"Invalid data types: {invalid}. Valid types: {valid_types}"
                )
        
        return value


