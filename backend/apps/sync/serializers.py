class ClearSyncDataRequestSerializer(serializers.Serializer):
    """
    Serializer for clearing sync data request.
    """
    clear_actions = serializers.BooleanField(
        required=False,
        default=False,
        help_text="Clear all sync actions"
    )
    clear_conflicts = serializers.BooleanField(
        required=False,
        default=False,
        help_text="Clear all conflicts"
    )
    clear_logs = serializers.BooleanField(
        required=False,
        default=False,
        help_text="Clear all sync logs"
    )
    older_than_days = serializers.IntegerField(
        required=False,
        default=30,
        min_value=1,
        max_value=365,
        help_text="Only clear data older than this many days"
    )
    
    def validate(self, data):
        """Ensure at least one clear option is selected."""
        if not any([
            data.get('clear_actions'),
            data.get('clear_conflicts'),
            data.get('clear_logs')
        ]):
            raise serializers.ValidationError(
                "At least one clear option must be selected"
            )
        return data