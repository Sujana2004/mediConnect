class PushRequestSerializer(serializers.Serializer):
    """
    Serializer for push sync request.
    """
    batch_id = serializers.CharField(
        max_length=100,
        help_text="Client-generated batch ID for idempotency"
    )
    actions = SyncActionInputSerializer(
        many=True,
        help_text="List of offline actions to sync"
    )
    device_info = serializers.JSONField(
        required=False,
        help_text="Device information"
    )
    
    def validate_actions(self, value):
        """Validate actions list."""
        if not value:
            raise serializers.ValidationError("At least one action is required")
        if len(value) > 50:
            raise serializers.ValidationError("Maximum 50 actions per request")
        
        # Check for duplicate client_action_ids within batch
        action_ids = [a['client_action_id'] for a in value]
        if len(action_ids) != len(set(action_ids)):
            raise serializers.ValidationError(
                "Duplicate client_action_id found in batch"
            )
        
        return value


